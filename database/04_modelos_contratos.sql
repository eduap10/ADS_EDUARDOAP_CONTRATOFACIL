CREATE TABLE IF NOT EXISTS modelos_contrato (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titulo VARCHAR(160) NOT NULL,
 conteudo TEXT NOT NULL,
 criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS contratos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 colaborador_id BIGINT NOT NULL REFERENCES colaboradores(id) ON DELETE RESTRICT,
 modelo_id BIGINT REFERENCES modelos_contrato(id) ON DELETE SET NULL,
 titulo VARCHAR(160) NOT NULL,
 conteudo TEXT NOT NULL,
 situacao VARCHAR(20) NOT NULL DEFAULT 'RASCUNHO',
 criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_contratos_situacao CHECK (situacao IN ('RASCUNHO','FINALIZADO','CANCELADO'))
);
CREATE INDEX IF NOT EXISTS idx_contratos_colaborador ON contratos(colaborador_id);
CREATE INDEX IF NOT EXISTS idx_contratos_modelo ON contratos(modelo_id);
