-- Execute no banco contratofacil com o usuario contratofacil_app.
-- Cria apenas a estrutura de login. O administrador inicial e criado pela tela de primeiro acesso.
BEGIN;

DO $$
BEGIN
    IF current_database() <> 'contratofacil' OR current_user <> 'contratofacil_app' THEN
        RAISE EXCEPTION 'Execute somente em contratofacil como contratofacil_app.';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(60) NOT NULL UNIQUE,
    senha_hash VARCHAR(64) NOT NULL,
    senha_salt VARCHAR(32) NOT NULL,
    perfil VARCHAR(10) NOT NULL DEFAULT 'USUARIO',
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('ADMIN', 'USUARIO'))
);
COMMIT;
