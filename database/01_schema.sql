-- Executar no banco contratofacil com o usuario da aplicacao.
BEGIN;
DO $$
BEGIN
    IF current_database() <> 'contratofacil' OR current_user <> 'contratofacil_app' THEN
        RAISE EXCEPTION 'Execute somente em contratofacil como contratofacil_app.';
    END IF;
END $$;
CREATE TABLE IF NOT EXISTS colaboradores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula VARCHAR(20) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    cargo VARCHAR(100),
    cpf VARCHAR(14),
    email VARCHAR(150)
);
CREATE INDEX IF NOT EXISTS idx_colaboradores_nome ON colaboradores (nome);
COMMIT;
