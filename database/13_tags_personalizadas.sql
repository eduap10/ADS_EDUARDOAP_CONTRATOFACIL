-- Como ler este script: Estrutura de tags definidas na aplicação; o mecanismo de substituição consulta esses campos na emissão.
-- SQL = definição/consulta de dados. Não é executado automaticamente só por atualizar o Git.
-- Cadastro seguro de campos adicionais para os modelos.
-- Pré-requisitos: banco contratofacil, usuário contratofacil_app.
BEGIN;
DO $$
BEGIN
 IF current_database() <> 'contratofacil' OR current_user <> 'contratofacil_app' THEN
   RAISE EXCEPTION 'Execute somente em contratofacil como contratofacil_app.';
 END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.tags_personalizadas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(40) NOT NULL UNIQUE CHECK (codigo ~ '^[a-z][a-z0-9_]{2,39}$'),
  nome VARCHAR(100) NOT NULL,
  descricao VARCHAR(250),
  tipo VARCHAR(25) NOT NULL CHECK (tipo IN
       ('TEXTO_FIXO','CAMPO_FICHA','DATA_ATUAL','HORA_ATUAL','DATA_HORA_ATUAL','ANO_ATUAL')),
  referencia VARCHAR(90),
  valor_fixo VARCHAR(500),
  ativo BOOLEAN NOT NULL DEFAULT TRUE,
  criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMIT;
