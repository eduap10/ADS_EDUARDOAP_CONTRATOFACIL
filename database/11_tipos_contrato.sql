-- Novo cadastro de tipos, mantendo modelos/contratos já cadastrados.
-- Executar em contratofacil, como contratofacil_app, após 08_categorias_documentos.sql.
BEGIN;
DO $$
BEGIN
  IF current_database() <> 'contratofacil' OR current_user <> 'contratofacil_app' THEN
    RAISE EXCEPTION 'Execute apenas em contratofacil como contratofacil_app.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.tipos_contrato (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    descricao VARCHAR(250),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    codigo_legado VARCHAR(40) UNIQUE
);

INSERT INTO public.tipos_contrato (nome, descricao, codigo_legado) VALUES
('Descrição de cargo', 'Descrição das atividades e responsabilidades.', 'DESCRICAO_CARGO'),
('Consentimento com políticas da empresa', 'Aceite das políticas internas.', 'CONSENTIMENTO_POLITICAS'),
('Termo de uso de vale-transporte', 'Condições de utilização do benefício.', 'VALE_TRANSPORTE'),
('Contrato de trabalho', 'Instrumento de formalização do vínculo.', 'CONTRATO_TRABALHO'),
('Termo de segurança da informação', 'Compromissos de proteção de informações.', 'SEGURANCA_INFORMACAO'),
('Outros', 'Demais documentos.', 'OUTROS')
ON CONFLICT (codigo_legado) DO NOTHING;

ALTER TABLE public.modelos_contrato
    ADD COLUMN IF NOT EXISTS tipo_id BIGINT REFERENCES public.tipos_contrato(id) ON DELETE RESTRICT;
ALTER TABLE public.contratos
    ADD COLUMN IF NOT EXISTS tipo_id BIGINT REFERENCES public.tipos_contrato(id) ON DELETE RESTRICT;

UPDATE public.modelos_contrato AS m SET tipo_id = t.id
FROM public.tipos_contrato AS t
WHERE m.tipo_id IS NULL AND t.codigo_legado = m.categoria;

UPDATE public.contratos AS c SET tipo_id = t.id
FROM public.tipos_contrato AS t
WHERE c.tipo_id IS NULL AND t.codigo_legado = c.categoria;

CREATE INDEX IF NOT EXISTS idx_modelos_tipo ON public.modelos_contrato(tipo_id);
CREATE INDEX IF NOT EXISTS idx_contratos_tipo ON public.contratos(tipo_id);
COMMIT;
